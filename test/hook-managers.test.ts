test("husky ≤8 (core.hooksPath=.husky, tracked): nothing with an absolute path is written into the committed hooks dir", () => {
  const r = repo();
  try {
    mkdirSync(join(r, ".husky", "_"), { recursive: true });
    writeFileSync(join(r, ".husky", "_", ".gitignore"), "*\n");
    writeFileSync(join(r, ".husky", "_", "husky.sh"), "#!/usr/bin/env sh\n# husky\n");
    const userHook = '#!/usr/bin/env sh\n. "$(dirname -- "$0")/_/husky.sh"\n\nnpm test\n';
    writeFileSync(join(r, ".husky", "pre-commit"), userHook);
    git(r, "add", ".husky/pre-commit");
    git(r, "commit", "-qm", "husky");
    git(r, "config", "core.hooksPath", ".husky");

    const results = [
      installPostCommitHook(r, LOCAL_INV),
      installPreCommitHook(r, LOCAL_INV),
      installPostMergeHook(r, LOCAL_INV),
      installPostCheckoutHook(r, LOCAL_INV),
    ];
    for (const res of results) {
      assert.equal(res.action, "managed-elsewhere");
      assert.equal(res.manager, "husky-legacy");
      assert.ok(!res.snippet?.includes(process.execPath));
    }
    assert.equal(readFileSync(join(r, ".husky", "pre-commit"), "utf8"), userHook);
    for (const file of allFiles(join(r, ".husky"))) {
      const text = readFileSync(file, "utf8");
      assert.ok(!text.includes(process.execPath), `${file} must not carry this machine's node path`);
      assert.doesNotMatch(text, /# >>> hunch/, `${file} must not get a hunch block`);
    }
    assert.equal(existsSync(join(r, ".husky", "post-commit")), false);
    assert.equal(git(r, "status", "--porcelain"), "", "the work tree stays clean");
  } finally { rmSync(r, { recursive: true, force: true }); }
});

