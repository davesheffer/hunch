/**
 * Issue #311: Hunch's appended hook blocks must never be written where they are
 * dead (pre-commit framework `exec`, husky v9 `.husky/_/h` → `exit $c`, any
 * trailing exec/exit) or where they would commit this machine's CLI path
 * (husky ≤8 / tracked core.hooksPath). Every fixture is a fresh temp repo —
 * never a real checkout or worktree (con_38bf8aa397).
 */
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, rmSync, readFileSync, writeFileSync, mkdirSync, existsSync, readdirSync, statSync, realpathSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { execFileSync, spawnSync } from "node:child_process";
import {
  installPostCommitHook, installPreCommitHook, installPostMergeHook, installPostCheckoutHook,
  hookStatus, hookReport, formatHookInstall, terminalExitLine, PORTABLE_HOOK_INVOCATION,
} from "../src/integrations/hooks.js";

const PROJECT_ROOT = process.cwd();
const TSX = join(PROJECT_ROOT, "node_modules/tsx/dist/cli.mjs");
const CLI = join(PROJECT_ROOT, "src/cli/index.ts");
// A machine-local invocation carrying this machine's absolute paths — exactly
// what must never land in a tracked file.
const LOCAL_INV = `${JSON.stringify(process.execPath)} ${JSON.stringify(CLI)}`;

function git(root: string, ...args: string[]): string {
  return execFileSync("git", args, { cwd: root, encoding: "utf8", env: { ...process.env, GIT_CONFIG_NOSYSTEM: "1" }, stdio: ["ignore", "pipe", "pipe"] }).trim();
}

function repo(prefix = "hunch-hookmgr-"): string {
  const r = realpathSync.native(mkdtempSync(join(tmpdir(), prefix)));
  git(r, "init", "-q", "-b", "main");
  git(r, "config", "user.email", "hooks@test.invalid");
  git(r, "config", "user.name", "Hook Managers");
  git(r, "config", "commit.gpgsign", "false");
  return r;
}

function preCommitFrameworkHook(hookType: string): string {
  return [
    "#!/usr/bin/env bash",
    "# File generated by pre-commit: https://pre-commit.com",
    "# ID: 138fd403232d2ddd5efb44317e38bf03",
    "",
    "# start templated",
    "INSTALL_PYTHON=/usr/bin/python3",
    `ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=${hookType})`,
    "# end templated",
    "",
    'HERE="$(cd "$(dirname "$0")" && pwd)"',
    'ARGS+=(--hook-dir "$HERE" -- "$@")',
    "",
    'if [ -x "$INSTALL_PYTHON" ]; then',
    '    exec "$INSTALL_PYTHON" -mpre_commit "${ARGS[@]}"',
    "elif command -v pre-commit > /dev/null; then",
    '    exec pre-commit "${ARGS[@]}"',
    "else",
    "    echo '`pre-commit` not found.  Did you install it into your venv?' 1>&2",
    "    exit 1",
    "fi",
    "",
  ].join("\n");
}

const HUSKY_H = [
  "#!/usr/bin/env sh",
  '[ "$HUSKY" = "2" ] && set -x',
  'n=$(basename "$0")',
  's=$(dirname "$(dirname "$0")")/$n',
  "",
  '[ ! -f "$s" ] && exit 0',
  "",
  'i="${XDG_CONFIG_HOME:-$HOME/.config}/husky/init.sh"',
  '[ -f "$i" ] && . "$i"',
  "",
  '[ "${HUSKY-}" = "0" ] && exit 0',
  "",
  'export PATH="node_modules/.bin:$PATH"',
  'sh -e "$s" "$@"',
  "c=$?",
  "",
  '[ $c != 0 ] && echo "husky - $n script failed (code $c)"',
  '[ $c = 127 ] && echo "husky - command not found in PATH=$PATH"',
  "exit $c",
  "",
].join("\n");
const HUSKY_STUB = '#!/usr/bin/env sh\n. "${0%/*}/h"\n';

function huskyV9(r: string): void {
  mkdirSync(join(r, ".husky", "_"), { recursive: true });
  writeFileSync(join(r, ".husky", "_", ".gitignore"), "*\n");
  writeFileSync(join(r, ".husky", "_", "h"), HUSKY_H);
  for (const name of ["pre-commit", "post-commit", "post-merge", "post-checkout"]) writeFileSync(join(r, ".husky", "_", name), HUSKY_STUB);
  writeFileSync(join(r, ".husky", "pre-commit"), "npm test\n");
  git(r, "config", "core.hooksPath", ".husky/_");
}

function allFiles(dir: string): string[] {
  if (!existsSync(dir)) return [];
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? allFiles(p) : [p];
  });
}

test("terminalExitLine: unconditional exec/exit and all-branch if/else exits are terminal; conditional exits are not", () => {
  assert.ok(terminalExitLine(preCommitFrameworkHook("pre-commit")));
  assert.equal(terminalExitLine("#!/bin/sh\nnpm test\nexit 0\n"), "exit 0");
  assert.equal(terminalExitLine("#!/bin/sh\nexec lint-staged\n"), "exec lint-staged");
  assert.equal(terminalExitLine(HUSKY_H), "exit $c");
  assert.equal(terminalExitLine("#!/bin/sh\n[ -f x ] || exit 0\necho ok\n"), null);
  assert.equal(terminalExitLine("#!/bin/sh\nif [ -z \"$X\" ]; then\n  exit 1\nfi\necho ok\n"), null);
  assert.equal(terminalExitLine("#!/bin/sh\nif [ -z \"$X\" ]; then\n  exit 1\nfi\n"), null, "no else branch: falls through");
  assert.equal(terminalExitLine("#!/bin/sh\necho user-hook\n"), null);
  assert.equal(terminalExitLine("#!/bin/sh\nfail() {\nexit 1\n}\nnpm test || fail\n"), null, "exit inside an unindented function body");
  assert.equal(terminalExitLine("#!/bin/sh\nif [ -n \"$SKIP\" ]; then\nexit 0\nfi\nnpm test\n"), null, "exit inside an unindented if");
  assert.equal(terminalExitLine("#!/bin/sh\nif [ -n \"$SKIP\" ]; then exit 0; fi\n  exec ./next-hook\n"), "exec ./next-hook", "one-line if closes; indented top-level exec is terminal");
  assert.equal(terminalExitLine("#!/bin/sh\nfor f in a b; do\n  echo $f\ndone\nexit 0\n"), "exit 0");
});

test("pre-commit framework: install writes nothing, returns a repo: local snippet, and status is not installed", () => {
  const r = repo();
  try {
    const hookPath = join(r, ".git", "hooks", "pre-commit");
    const generated = preCommitFrameworkHook("pre-commit");
    writeFileSync(hookPath, generated);
    const res = installPreCommitHook(r, LOCAL_INV);
    assert.equal(res.action, "managed-elsewhere");
    assert.equal(res.manager, "pre-commit");
    assert.equal(readFileSync(hookPath, "utf8"), generated, "the generated hook is untouched");
    assert.equal(res.path, join(r, ".pre-commit-config.yaml"));
    assert.match(res.snippet ?? "", /- repo: local/);
    assert.match(res.snippet ?? "", /id: hunch-pre-commit/);
    assert.match(res.snippet ?? "", /stages: \[pre-commit\]/);
    assert.ok((res.snippet ?? "").includes(PORTABLE_HOOK_INVOCATION));
    assert.ok(!(res.snippet ?? "").includes(process.execPath), "tracked config never gets this machine's node path");
    assert.equal(existsSync(join(r, ".pre-commit-config.yaml")), false, "Hunch never edits the manager's config itself");
    assert.equal(hookReport(r).preCommit.state, "missing");

    // The user adds the snippet: now it's installed, and a re-run is a no-op.
    writeFileSync(join(r, ".pre-commit-config.yaml"), `repos:\n${res.snippet}\n`);
    assert.equal(hookReport(r).preCommit.state, "installed");
    assert.equal(hookStatus(r).preCommit, true);
    assert.equal(installPreCommitHook(r, LOCAL_INV).action, "unchanged");
    assert.equal(readFileSync(hookPath, "utf8"), generated);
  } finally { rmSync(r, { recursive: true, force: true }); }
});

