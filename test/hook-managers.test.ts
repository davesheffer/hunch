test("husky v9: nothing is appended to .husky/_ (dead after exit $c, regenerated on install); snippet targets .husky/<hook>", () => {
  const r = repo();
  try {
    huskyV9(r);
    const before = Object.fromEntries(allFiles(join(r, ".husky")).map((p) => [p, readFileSync(p, "utf8")]));
    const results = [
      installPostCommitHook(r, LOCAL_INV),
      installPreCommitHook(r, LOCAL_INV),
      installPostMergeHook(r, LOCAL_INV),
      installPostCheckoutHook(r, LOCAL_INV),
    ];
    const after = Object.fromEntries(allFiles(join(r, ".husky")).map((p) => [p, readFileSync(p, "utf8")]));
    assert.deepEqual(after, before, "no husky file created or modified");
    for (const res of results) {
      assert.equal(res.action, "managed-elsewhere");
      assert.equal(res.manager, "husky");
      assert.ok(res.snippet?.includes(PORTABLE_HOOK_INVOCATION));
      assert.ok(!res.snippet?.includes(process.execPath), "husky scripts are tracked — no absolute node path");
    }
    assert.equal(results[0]!.path, join(r, ".husky", "post-commit"));
    // post-merge carries BOTH managed blocks in one snippet.
    assert.match(results[2]!.snippet ?? "", /# >>> hunch post-merge >>>/);
    assert.match(results[2]!.snippet ?? "", /# >>> hunch post-merge \(repair-provenance\) >>>/);
    assert.deepEqual(hookStatus(r), { postCommit: false, preCommit: false, postMerge: false, postCheckout: false });

    // CLI rendering surfaces the reason and the snippet.
    const lines = formatHookInstall(r, "post-commit hook", results[0]!, " (learning loop)").join("\n");
    assert.match(lines, /⚠ post-commit hook NOT installed — husky v9/);
    assert.match(lines, /add this to \.husky\/post-commit yourself/);

    // The user adds the snippets to husky's own scripts → installed, re-run unchanged.
    writeFileSync(join(r, ".husky", "post-commit"), `${results[0]!.snippet}\n`);
    writeFileSync(join(r, ".husky", "post-merge"), `${results[2]!.snippet}\n`);
    assert.equal(hookStatus(r).postCommit, true);
    assert.equal(hookStatus(r).postMerge, true);
    assert.equal(installPostCommitHook(r, LOCAL_INV).action, "unchanged");
    assert.equal(installPostMergeHook(r, LOCAL_INV).action, "unchanged");
  } finally { rmSync(r, { recursive: true, force: true }); }
});

test("husky v9: a reachable block in husky's own script whose launcher is gone is stale, and the install says to replace it", () => {
  const r = repo();
  try {
    huskyV9(r);
    // Reachable (husky's own script), but the absolute launcher it points at is
    // gone after a reinstall — never executed here, only read.
    const dead = join(r, "gone", "bin", "hunch");
    writeFileSync(join(r, ".husky", "post-commit"), `# >>> hunch post-commit >>>\n${dead} sync --from-hook --quiet\n# <<< hunch post-commit <<<\n`);
    const report = hookReport(r);
    assert.equal(report.postCommit.state, "stale");
    assert.equal(hookStatus(r).postCommit, false);

    const res = installPostCommitHook(r, "hunch");
    assert.equal(res.action, "managed-elsewhere");
    assert.match(res.reason ?? "", /stale/, "a stale block must not be reported as 'a hook manager owns this hook'");
    assert.ok(res.snippet?.includes(PORTABLE_HOOK_INVOCATION));
  } finally { rmSync(r, { recursive: true, force: true }); }
});

