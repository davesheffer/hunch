const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = path.join(repoRoot, "site", "index.html");
const siteOrigin = "https://www.hunchmemory.com";
const normalizeLf = (value) => value.replace(/\r\n?/g, "\n");

function escAttr(value) {
  return value.replaceAll("&", "&amp;").replaceAll('"', "&quot;");
}

function replaceRequired(html, from, to, locale) {
  if (!html.includes(from)) throw new Error(`[${locale}] source fragment not found: ${from.slice(0, 100)}`);
  return html.replaceAll(from, to);
}

function findLines(lines, wanted, from) {
  outer: for (let k = from; k + wanted.length <= lines.length; k++) {
    for (let t = 0; t < wanted.length; t++) if (lines[k + t] !== wanted[t]) continue outer;
    return k;
  }
  return -1;
}

// Hunks replace whole lines in order; each must be found at or after the end of the previous one, so an
// English edit that a translation covers stops the build instead of shipping stale or mixed copy.
function applyHunks(html, hunks, locale) {
  const lines = html.split("\n");
  let cursor = 0;
  for (const [index, { en, tr }] of hunks.entries()) {
    const at = findLines(lines, en, cursor);
    if (at < 0) throw new Error(`[${locale}] homepage hunk ${index + 1} source fragment not found after line ${cursor + 1}: ${en.join(" ").trim().slice(0, 100)}`);
    lines.splice(at, en.length, ...tr);
    cursor = at + tr.length;
  }
  return lines.join("\n");
}

const visibleText = (html) => html
  .replace(/<script\b[\s\S]*?<\/script>/gi, " ").replace(/<style\b[\s\S]*?<\/style>/gi, " ").replace(/<!--[\s\S]*?-->/g, " ")
  .replace(/<pre\b[\s\S]*?<\/pre>/gi, " ").replace(/<code\b[\s\S]*?<\/code>/gi, " ").replace(/<[^>]+>/g, " ")
  .replace(/&[a-z#0-9]+;/gi, " ").replace(/\s+/g, " ");

// Every English sentence of prose (headings, paragraphs, list items, captions) must be gone from a
// localized page. This catches copy added to site/index.html without a matching translation hunk.
const source = normalizeLf(await readFile(sourcePath, "utf8"));
const englishProse = [...new Set([...source.replace(/<script\b[\s\S]*?<\/script>/gi, "").matchAll(/<(h[1-4]|p|li|figcaption|dd|dt|summary)\b[^>]*>([\s\S]*?)<\/\1>/gi)]
  .map((match) => visibleText(match[2]).trim()).filter((text) => text.length >= 24 && /[a-z]{3,} [a-z]{3,}/i.test(text)))];

for (const [locale, copy] of Object.entries(homepageLocales)) {
  let html = source;
  html = replaceRequired(html, '<html lang="en">', `<html lang="${locale}"${copy.dir === "rtl" ? ' dir="rtl"' : ""}>`, locale);
  html = replaceRequired(html, '<meta property="og:url" content="https://www.hunchmemory.com/" />', `<meta property="og:url" content="${siteOrigin}/${locale}" />`, locale);
  html = replaceRequired(html, '<meta property="og:locale" content="en_US" />', `<meta property="og:locale" content="${copy.ogLocale}" />`, locale);
  html = replaceRequired(html, '<link rel="canonical" href="https://www.hunchmemory.com/" />', `<link rel="canonical" href="${siteOrigin}/${locale}" />`, locale);
  html = replaceRequired(html, '<a class="brand" href="/">', `<a class="brand" href="/${locale}">`, locale);
  html = replaceRequired(html, '<option value="/" selected>EN</option>', '<option value="/">EN</option>', locale);
  html = replaceRequired(html, `<option value="/${locale}">${locale.toUpperCase()}</option>`, `<option value="/${locale}" selected>${locale.toUpperCase()}</option>`, locale);
  html = html.replaceAll('href="/blog/post?slug=the-state-layer"', `href="/${locale}/blog/post?slug=the-state-layer"`);
  html = html.replaceAll('href="/blog/"', `href="/${locale}/blog"`);
  html = html.replaceAll('href="/changelog"', `href="/${locale}/changelog"`);
  html = applyHunks(html, copy.hunks, locale);
  html = html.replace("<!DOCTYPE html>", "<!DOCTYPE html>\n<!-- Generated by tooling/generate-site-locales.mjs. Edit site/index.html and tooling/homepage-locales.mjs, then regenerate. -->");

  const visible = visibleText(html);
  const leaked = englishProse.filter((text) => visible.includes(text));
  if (leaked.length) throw new Error(`[${locale}] untranslated visible English: ${leaked.slice(0, 3).map((text) => JSON.stringify(text.slice(0, 80))).join(", ")}`);

  const targetDir = path.join(repoRoot, "site", locale);
  await mkdir(targetDir, { recursive: true });
  await writeFile(path.join(targetDir, "index.html"), html, "utf8");
  console.log(`generated site/${locale}/index.html (${copy.dir}, ${copy.hunks.length} hunks)`);
}

