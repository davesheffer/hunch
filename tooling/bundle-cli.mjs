#!/usr/bin/env node
/**
 * Post-tsc build step: bundle the CLI so a hook process loads ONE module
 * instead of ~540 (381 of Hunch's own). Every agent hook is a fresh process,
 * and ESM resolve/stat/read/compile per module was ~320 ms of each call on
 * Windows.
 *
 *   dist/cli/index.bundle.js  - esbuild bundle of tsc's dist/cli/index.js
 *   dist/cli/hook.bundle.js   - esbuild bundle of dist/cli/hookMain.js: only what
 *                               `hunch hook` needs (no Commander, no other
 *                               commands' imports; ~100 ms of schema construction
 *                               a hook never uses)
 *   dist/cli/hook-client.bundle.js - the opt-in hook daemon client: tries the warm
 *                               daemon, else hands the same stdin to hook.bundle.js
 *   dist/cli/index.js         - tiny entry: Node-version gate, compile cache,
 *                               then the hook bundle for a plain `hook` argv
 *                               (same rule as fastHookArgs in hookMain.ts) or
 *                               the full bundle otherwise. Keeps the published
 *                               path that installed hooks and `bin` already
 *                               point at.
 *
 * Every other tsc output file stays in dist/: tests, the package's type
 * exports, and detached workers (update check, replay) import those directly.
 * Native tree-sitter grammars and the optional embeddings peer stay external.
 */
import { build } from "esbuild";
import { readFileSync, renameSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const cli = fileURLToPath(new URL("../dist/cli/", import.meta.url));
const entry = `${cli}index.js`;
const bundle = `${cli}index.bundle.js`;
const MARKER = "// hunch:bundle-entry";

if (readFileSync(entry, "utf8").includes(MARKER)) {
  throw new Error("dist/cli/index.js is already the bundle entry; run `npm run build` (it cleans dist first)");
}

const bundles = [
  { entry, bundle },
  { entry: `${cli}hookMain.js`, bundle: `${cli}hook.bundle.js` },
  // Hook daemon client (default on; HUNCH_HOOK_DAEMON=0 opts out): loads neither handler nor store.
  { entry: `${cli}hookClient.js`, bundle: `${cli}hook-client.bundle.js` },
];
for (const { entry: input, bundle: output } of bundles) {
  await build({
    entryPoints: [input],
    outfile: `${output}.tmp`,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    external: ["tree-sitter", "tree-sitter-*", "@tree-sitter-grammars/*", "@huggingface/transformers"],
    // Bundled CommonJS dependencies call require() for Node builtins; ESM has
    // no require, so give the bundle one.
    banner: { js: "import { createRequire as __hunchCreateRequire } from \"node:module\"; const require = __hunchCreateRequire(import.meta.url);" },
    legalComments: "inline",
    // Keep module paths as seen from the project. Resolving a symlinked
    // node_modules (the Matrix release verifier links the workspace's into its
    // clone) to its real path changes every `// <path>` comment, so the clone's
    // bundle would differ from the tagged workspace's and fail the release.
    preserveSymlinks: true,
    logLevel: "warning",
  });
  if (/^\/\/ \.\.\//m.test(readFileSync(`${output}.tmp`, "utf8"))) {
    throw new Error("bundle references a module outside the project; the build would not be byte-reproducible");
  }
  renameSync(`${output}.tmp`, output);
}

// The gate must run before the bundle is even linked (the bundle imports
// node:sqlite), and compile caching must be on before the bundle is compiled,
// hence a separate module and a dynamic import.
const shim = `#!/usr/bin/env node
${MARKER} (generated by tooling/bundle-cli.mjs; do not edit)
import "./preflight.js";
import * as nodeModule from "node:module";
try { nodeModule.enableCompileCache?.(); } catch { /* cache is an optimization only */ }
const a = process.argv.slice(2);
const fastHook = a[0] === "hook" && (a.length === 1
  || (a.length === 3 && a[1] === "--provider" && !!a[2])
  || (a.length === 2 && a[1].startsWith("--provider=") && a[1].length > 11));
const daemonOff = /^(0|false|off)$/i.test((process.env.HUNCH_HOOK_DAEMON ?? "").trim());
const hookBundle = fastHook && !daemonOff ? "./hook-client.bundle.js" : "./hook.bundle.js";
await import(fastHook ? hookBundle : "./index.bundle.js");
`;
writeFileSync(`${entry}.tmp`, shim);
renameSync(`${entry}.tmp`, entry);
